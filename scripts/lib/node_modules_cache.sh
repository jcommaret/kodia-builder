#!/usr/bin/env bash
# Cache des node_modules entre deux runs, sur le modèle du pipeline de VS Code
# (build/azure-pipelines/*/product-build-*-node-modules.yml) :
# - le workflow calcule la clé avec build/azure-pipelines/common/computeNodeModulesCacheKey.ts (package.json,
#   package-lock.json et .npmrc de tous les dossiers de build/npm/dirs.ts), restaure .build/node_modules_cache/cache.tgz
#   et l'extrait dans vscode/ ; il passe alors NODE_MODULES_RESTORED=true au script de packaging ;
# - le script de packaging saute alors npm ci et mixin-npm ; sinon il les lance puis appelle nm_cache_archive,
#   juste après l'installation, pour que l'archive ne contienne rien de ce que le build écrit ensuite ;
# - le workflow sauvegarde l'archive (actions/cache/save) quand elle n'a pas été restaurée.
# Les fonctions s'appellent depuis le dossier vscode/.

nm_cache_restored() {
  [[ "${NODE_MODULES_RESTORED}" == "true" ]]
}

nm_cache_archive() {
  echo "Archiving node_modules for the cache"
  mkdir -p .build/node_modules_cache
  node build/azure-pipelines/common/listNodeModules.ts .build/node_modules_list.txt
  tar -czf .build/node_modules_cache/cache.tgz --files-from .build/node_modules_list.txt
}
